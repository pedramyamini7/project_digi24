<?php

require "../config/config.php";


// =====================================================
// گرفتن ID مقاله از URL
// =====================================================

$article_id = isset($_GET['id'])
    ? (int) $_GET['id']
    : 0;


// =====================================================
// بررسی ID
// =====================================================

if ($article_id <= 0) {

    header("Location: jadval_maghale.php");
    exit;

}


// =====================================================
// گرفتن عکس مقاله قبل از حذف
// =====================================================

$sql_get = "
    SELECT image
    FROM maghale_dakhel
    WHERE id = $article_id
    LIMIT 1
";

$result_get = mysqli_query(
    $conn,
    $sql_get
);


// =====================================================
// بررسی Query
// =====================================================

if (!$result_get) {

    die(
        "خطا در دریافت مقاله: "
        . mysqli_error($conn)
    );

}


$article = mysqli_fetch_assoc($result_get);


// =====================================================
// اگر مقاله وجود نداشت
// =====================================================

if (!$article) {

    header("Location: jadval_maghale.php");
    exit;

}


// =====================================================
// نام عکس اصلی
// =====================================================

$oldImage = $article['image'] ?? '';


// =====================================================
// حذف مقاله از دیتابیس
// =====================================================

$sql_delete = "
    DELETE FROM maghale_dakhel
    WHERE id = $article_id
    LIMIT 1
";

$result_delete = mysqli_query(
    $conn,
    $sql_delete
);


// =====================================================
// بررسی حذف
// =====================================================

if (!$result_delete) {

    die(
        "خطا در حذف مقاله: "
        . mysqli_error($conn)
    );

}


// =====================================================
// حذف عکس اصلی از uploads
// =====================================================

if (!empty($oldImage)) {

    $imagePath =
        "../uploads/" .
        basename($oldImage);


    if (file_exists($imagePath)) {

        unlink($imagePath);

    }

}


// =====================================================
// بازگشت به جدول مقالات
// =====================================================

header(
    "Location: jadval_maghale.php?deleted=1"
);

exit;

?>
